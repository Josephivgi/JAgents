#!/usr/bin/env node
"use strict";

// Builds renderer/js/harness-logos.js from the official ACP Registry: each
// agent's own logo (16px, monochrome, currentColor), so the harness picker
// shows real logos offline and for agents that are not installed yet.
//   node scripts/sync-harness-logos.cjs
// Only shape elements and their drawing attributes are kept; scripts, links,
// event handlers and styles are dropped.

const fs = require("node:fs");
const path = require("node:path");

const REGISTRY_URL = "https://cdn.agentclientprotocol.com/registry/v1/latest/registry.json";
const OUT = path.join(__dirname, "..", "renderer", "js", "harness-logos.js");

const TAGS = new Set(["g", "path", "rect", "circle", "ellipse", "polygon", "polyline", "line", "defs", "clippath", "mask", "lineargradient", "radialgradient", "stop"]);
const ATTRS = new Set(["d", "x", "y", "x1", "x2", "y1", "y2", "cx", "cy", "r", "rx", "ry", "width", "height", "points", "fill", "stroke", "stroke-width", "stroke-linecap", "stroke-linejoin", "stroke-miterlimit", "fill-rule", "clip-rule", "opacity", "fill-opacity", "stroke-opacity", "transform", "id", "clip-path", "mask", "offset", "stop-color", "stop-opacity", "gradientunits", "gradienttransform"]);

function sanitize(svg, id) {
  const open = /<svg\b([^>]*)>/i.exec(svg);
  if (!open) throw new Error(id + ": no <svg> element");
  const vb = /viewBox\s*=\s*"([^"]+)"/i.exec(open[1]);
  const w = /\bwidth\s*=\s*"([\d.]+)/i.exec(open[1]);
  const h = /\bheight\s*=\s*"([\d.]+)/i.exec(open[1]);
  const viewBox = vb ? vb[1].trim() : "0 0 " + (w ? w[1] : 16) + " " + (h ? h[1] : 16);
  const inner = svg.slice(open.index + open[0].length, svg.lastIndexOf("</svg>"));
  // Prefix ids so two logos on one page never share a clip path or gradient.
  const prefix = "hl-" + id.replace(/[^a-z0-9]/gi, "") + "-";
  let out = "";
  const re = /<\/?\s*([a-zA-Z][\w:-]*)([^>]*?)(\/?)>/g;
  let m;
  while ((m = re.exec(inner))) {
    const tag = m[1].toLowerCase();
    if (!TAGS.has(tag)) continue;
    if (m[0].startsWith("</")) {
      out += "</" + m[1] + ">";
      continue;
    }
    const attrs = [];
    const are = /([a-zA-Z][\w:-]*)\s*=\s*("([^"]*)"|'([^']*)')/g;
    let a;
    while ((a = are.exec(m[2]))) {
      const name = a[1].toLowerCase();
      let value = a[3] != null ? a[3] : a[4];
      if (!ATTRS.has(name) || /javascript:|expression\(|url\((?!#)/i.test(value)) continue;
      if (name === "id") value = prefix + value;
      value = value.replace(/url\(#([^)]+)\)/g, "url(#" + prefix + "$1)");
      attrs.push(a[1] + '="' + value.replace(/"/g, "&quot;") + '"');
    }
    out += "<" + m[1] + (attrs.length ? " " + attrs.join(" ") : "") + (m[3] ? "/>" : ">");
  }
  return { viewBox, body: out.replace(/\s+/g, " ").trim() };
}

async function main() {
  const res = await fetch(REGISTRY_URL);
  if (!res.ok) throw new Error("registry: HTTP " + res.status);
  const registry = await res.json();
  const logos = {};
  for (const agent of registry.agents || []) {
    if (!agent.icon || !/^https:\/\//.test(agent.icon)) continue;
    try {
      const r = await fetch(agent.icon);
      if (!r.ok) throw new Error("HTTP " + r.status);
      logos[agent.id] = Object.assign({ name: agent.name }, sanitize(await r.text(), agent.id));
    } catch (error) {
      console.error("skipped " + agent.id + ": " + error.message);
    }
  }
  const ids = Object.keys(logos).sort();
  const body =
    "// Generated by scripts/sync-harness-logos.cjs from the ACP Registry. Each\n" +
    "// agent's own logo, monochrome in currentColor. Do not edit by hand.\n\n" +
    "export const HARNESS_LOGOS = {\n" +
    ids.map((id) => "  " + JSON.stringify(id) + ": " + JSON.stringify(logos[id]) + ",").join("\n") +
    "\n};\n";
  fs.writeFileSync(OUT, body);
  console.log("wrote " + ids.length + " logos to " + path.relative(process.cwd(), OUT));
}

main().catch((error) => {
  console.error(error.message);
  process.exit(1);
});
